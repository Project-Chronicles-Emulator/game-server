QuestCompanyRewards WorldQuestBook::company_rewards_earned(const WorldProgress &before,
                                                          const WorldProgress &after) const {
  QuestCompanyRewards rewards;
  for (const auto &[quest_id, quest] : after.quests) {
    if (!newly_completed(before, quest_id, quest)) {
      continue;
    }
    const auto *definition = catalog_->quest(quest_id);
    if (!definition) {
      continue;
    }
    const auto earned = company_unlocks_of(*definition);
    rewards.unlocks.insert(rewards.unlocks.end(), earned.begin(), earned.end());
    rewards.contribution += definition->value("company_contribution", std::int64_t{0});
  }
  return rewards;
}

