QuestResult WorldQuestBook::record_monster_defeat(std::uint64_t unit_id, int npc_cms_id,
                                                 const WorldProgress &current,
                                                 const QuestWorldView &view,
                                                 bool award_monster_experience,
                                                 const MonsterRewardReceipt *receipt) const {
  QuestResult result;
  auto next = current;

  // Kill records also gate world interactions that are not attached to a quest.
  for (const int record_id : catalog_->kill_play_records(npc_cms_id)) {
    if (!next.play_records.contains(record_id) &&
        next.play_records.size() >= kMaximumPlayRecords) {
      continue;
    }
    auto &count = next.play_records[record_id];
    if (count < std::numeric_limits<int>::max()) {
      ++count;
      result.packets.push_back({kPlayRecordUpdateNotification,
                                {{"play_record", {{"cms_id", record_id}, {"count", count}}}}});
    }
  }

  // A ServerOffered quest started by this monster also counts the defeat that started it.
  std::set<int> eligible_offers;
  if (receipt && receipt->allow_monster_offered_quests) {
    for (const int quest_id : catalog_->monster_quest_ids(npc_cms_id)) {
      const auto *definition = catalog_->quest(quest_id);
      if (!definition) {
        continue;
      }
      const auto before = receipt->quest_attempts.find(quest_id);
      const auto now = current.quests.find(quest_id);
      const bool eligible =
          (before == receipt->quest_attempts.end() && now == current.quests.end()) ||
          (before != receipt->quest_attempts.end() && before->second.abandoned &&
           now != current.quests.end() && now->second.abandoned &&
           now->second.attempt == before->second.attempt &&
           now->second.started_epoch_ms == before->second.started_epoch_ms);
      if (!eligible) {
        continue;
      }
      const bool offered_by_monster = std::ranges::any_of(
          definition->at("accept"),
          [&](const Json &rule) {
            return rule.at("kind") == "ServerOffered" &&
                   std::ranges::any_of(rule.at("monster_ids"), [&](const Json &id) {
                     return id.get<int>() == npc_cms_id;
                   });
          });
      if (!offered_by_monster) {
        continue;
      }
      if (!definition->at("conditions").empty() ||
          definition->value("require_gold", std::int64_t{0}) != 0 ||
          !definition->value("require_items", Json::array()).empty()) {
        // Condition inputs outside quest attempts are not yet captured at defeat time. Keep
        // the receipt pending instead of silently skipping or evaluating newer player state.
        throw std::runtime_error("Monster-offered quest requires unsupported defeat-time inputs");
      }
      eligible_offers.insert(quest_id);
    }
    offer_quests(OfferTrigger::Monster, npc_cms_id, next, view, result.packets,
                 &eligible_offers);
  } else if (!receipt) {
    offer_quests(OfferTrigger::Monster, npc_cms_id, next, view, result.packets);
  }

  const auto before_kill = next;
  for (const auto &[quest_id, previous] : before_kill.quests) {
    auto at_defeat = previous;
    if (receipt) {
      const auto eligible = receipt->quest_attempts.find(quest_id);
      const bool same_attempt = eligible != receipt->quest_attempts.end() &&
                                eligible->second.attempt == previous.attempt &&
                                eligible->second.started_epoch_ms == previous.started_epoch_ms &&
                                !eligible->second.complete && !eligible->second.abandoned;
      const bool offered_by_this_death = eligible_offers.contains(quest_id) &&
                                         (!current.quests.contains(quest_id) ||
                                          current.quests.at(quest_id).abandoned);
      if (!same_attempt && !offered_by_this_death) {
        continue;
      }
      if (same_attempt) {
        at_defeat.objectives = eligible->second.objectives;
      }
    }
    const auto *definition = catalog_->quest(quest_id);
    if (!definition || previous.complete || previous.abandoned ||
        previous.credited_kills.contains(unit_id)) {
      continue;
    }
    auto &quest = next.quests.at(quest_id);
    bool changed = false;
    for (const auto &objective : definition->at("progresses")) {
      if (!hunts_monster(objective, npc_cms_id) ||
          !objective_ready(*definition, at_defeat, objective.at("group"))) {
        continue;
      }
      auto &count = quest.objectives[objective.at("sequence").get<int>()];
      const auto required = quest_rules::objective_required_count(objective);
      const bool hunt = objective.at("kind") == "HuntMonster";
      const int credit = hunt ? 1 : ethereal_amount(objective.at("parameters"));
      if (count < required && credit > 0) {
        count = std::min(required, count + credit);
        changed = true;
      }
    }
    if (!changed) {
      continue;
    }
    if (quest.credited_kills.size() >= kMaximumCreditedKills) {
      throw std::runtime_error("World quest kill receipt limit exceeded");
    }
    quest.credited_kills.insert(unit_id);
    result.packets.push_back({kQuestUpdate, {{"quest", quest_json(quest_id, quest)}}});
    if (definition->at("auto_complete").get<bool>() &&
        quest_rules::objectives_complete(*definition, quest)) {
      complete_quest(quest_id, next, view, result.packets);
    }
  }

  if (progression_ && award_monster_experience) {
    grant_quest_experience(progression_->monster_experience(npc_cms_id), next, result.packets);
  }
  if (next != current) {
    if (next.revision == std::numeric_limits<std::int64_t>::max()) {
      throw std::runtime_error("World monster reward revision exhausted");
    }
    ++next.revision;
    result.next = std::move(next);
  }
  return result;
}

QuestResult WorldQuestBook::gm_accept(int quest_id, bool check_conditions,
                                      const WorldProgress &current,
                                      const QuestWorldView &view) const {
  const auto *definition = catalog_->quest(quest_id);
  if (!definition || accepted_quest(current, quest_id) ||
      current.quests.size() >= kMaximumSavedQuests ||
      (check_conditions && !conditions_pass(*definition, current, view))) {
    return {};
  }

  QuestResult result;
  auto next = current;
  try {
    begin_quest(quest_id, next, view, result.packets, std::nullopt);
  } catch (const RuleError &) {
    // Supplies/rewards that cannot be granted leave the entire acceptance unchanged.
    return {};
  }
  result.next = std::move(next);
  return result;
}

WorldQuestBook::GmCompletion WorldQuestBook::gm_complete(const std::vector<int> &quest_ids,
                                                         const WorldProgress &current,
                                                         const QuestWorldView &view) const {
  GmCompletion completion;
  auto next = current;
  for (const int quest_id : quest_ids) {
    const auto *definition = catalog_->quest(quest_id);
    const auto *saved = accepted_quest(next, quest_id);
    if (!definition || (saved && saved->complete)) {
      ++completion.skipped;
      continue;
    }

    // Work on a copy so a failed reward leaves no partial quest state behind.
    auto attempt = next;
    std::vector<GameplayPacket> packets;
    try {
      if (!accepted_quest(attempt, quest_id)) {
        QuestProgress restarted;
        const auto tombstone = attempt.quests.find(quest_id);
        if (tombstone != attempt.quests.end()) {
          restarted.attempt = tombstone->second.attempt + 1;
          restarted.success_count = tombstone->second.success_count;
        } else {
          require(attempt.quests.size() < kMaximumSavedQuests, "BadRequest");
        }
        restarted.started_epoch_ms = view.now_epoch_ms;
        attempt.quests.insert_or_assign(quest_id, restarted);
        packets.push_back(
            {kQuestAccepted, {{"quest", quest_json(quest_id, attempt.quests.at(quest_id))}}});
      }

      auto &quest = attempt.quests.at(quest_id);
      for (const auto &objective : definition->at("progresses")) {
        const int sequence = objective.at("sequence");
        const int required = quest_rules::objective_required_count(objective);
        // Saved objective counters never decrease (storage invariant).
        quest.objectives[sequence] = std::max(quest.objectives[sequence], required);
      }

      if (reward_supported(*definition)) {
        complete_quest(quest_id, attempt, view, packets);
      } else {
        quest.complete = true;
        quest.success_count = std::max(quest.success_count, 1);
        packets.push_back({kQuestUpdate, {{"quest", quest_json(quest_id, quest)}}});
      }
    } catch (const RuleError &) {
      ++completion.skipped;
      continue;
    } catch (const Json::exception &) {
      ++completion.skipped;
      continue;
    }

    next = std::move(attempt);
    completion.result.packets.insert(completion.result.packets.end(),
                                     std::make_move_iterator(packets.begin()),
                                     std::make_move_iterator(packets.end()));
    ++completion.completed;
  }

  if (next != current) {
    completion.result.next = std::move(next);
  }
  return completion;
}

QuestResult WorldQuestBook::receive(std::uint16_t opcode, const Json &request,
                                    std::uint32_t sequence, const WorldProgress &current,
                                    const QuestWorldView &view) {
  QuestResult result;
  if (!handles(opcode)) {
    return result;
  }

  auto next = current;
  try {
    switch (opcode) {
    case kAcceptQuest:
      accept(request, next, view, result.packets);
      break;
    case kProgressQuest:
      progress(request, next, view, result.packets);
      break;
    case kClaimQuestReward:
      reward(request, next, view, result.packets);
      break;
    case kAbandonQuest:
      abandon(request, next, result.packets);
      break;
    case kJobBoardRequest:
      job_board_request(request, next, view, result.packets);
      break;
    case kStartDialogue:
      start_dialogue(request, next, view, result.packets);
      break;
    case kEndDialogue:
      dialogue_target_.reset();
      dialogue_npc_template_id_.reset();
      result.packets.push_back({kDialogueEnded, {{"player_unit_id", player_unit_id_}}});
      break;
    default:
      break;
    }
  } catch (const RuleError &error) {
    return error_result(error.code, sequence);
  } catch (const Json::exception &) {
    return error_result("BadRequest", sequence);
  } catch (const std::out_of_range &) {
    return error_result("BadRequest", sequence);
  }

  for (auto &packet : result.packets) {
    if (packet.opcode == kQuestAccepted) {
      packet.message["packet_seq"] = {{"seq", std::to_string(sequence)}};
    }
  }
  if (next != current) {
    result.next = std::move(next);
  }
  return result;
}

QuestResult WorldQuestBook::periodic_update(const WorldProgress &current,
                                            const QuestWorldView &view) const {
  QuestResult result;
  auto next = current;
  start_story_followups(next, view, result.packets);
  offer_quests(OfferTrigger::Map, 0, next, view, result.packets);
  refresh_active_quests(next, view, result.packets);
  if (next == current) {
    return result;
  }
  if (next.revision == std::numeric_limits<std::int64_t>::max()) {
    throw std::runtime_error("World quest periodic revision exhausted");
  }
  ++next.revision;
  result.next = std::move(next);
  return result;
}

QuestResult WorldQuestBook::refresh_gathered_items(const WorldProgress &current,
                                                      const QuestWorldView &view) const {
  QuestResult result;
  auto next = current;
  refresh_active_quests(next, view, result.packets, true);
  if (next == current) {
    return result;
  }
  if (next.revision == std::numeric_limits<std::int64_t>::max()) {
    throw std::runtime_error("Gathering quest item revision exhausted");
  }
  ++next.revision;
  result.next = std::move(next);
  return result;
}

const AnnouncedUnit *WorldQuestBook::nearby_npc(std::uint64_t unit_id,
                                                const QuestWorldView &view) const {
  const auto *unit = view.find_unit ? view.find_unit(unit_id) : nullptr;
  if (!unit || unit->npc_template_id <= 0) {
    return nullptr;
  }
  if (distance_squared(view.position, unit_point(unit->position)) >
      kInteractionRangeMm * kInteractionRangeMm) {
    return nullptr;
  }
  return unit;
}

bool WorldQuestBook::placement_nearby(std::uint64_t unit_id, const Json &placements,
                                      const QuestWorldView &view) const {
  // Placements belong to one world asset, like trigger volumes.
  const auto world = catalog_->world_of(view.position.map_id);
  for (const auto &placement : placements) {
    if (placement.at("world").get<std::string>() != world ||
        parse_unit_id(placement.at("unit_id")) != unit_id) {
      continue;
    }
    if (distance_squared(view.position, placement.at("center")) <=
        kInteractionRangeMm * kInteractionRangeMm) {
      return true;
    }
  }
  return false;
}

bool WorldQuestBook::doodad_matches(std::uint64_t unit_id, const Json &placements, int phase,
                                    const QuestWorldView &view) const {
  if (!placement_nearby(unit_id, placements, view)) {
    return false;
  }
  // Doodads whose phase the server does not track (no interaction flow on this server) are
  // accepted in any phase; the client only offers the action in the authored phase.
  const auto current_phase = view.doodad_phase ? view.doodad_phase(unit_id) : std::nullopt;
  return phase == 0 || !current_phase || *current_phase == phase;
}

bool WorldQuestBook::memo_matches(const Json &request, const Json &objective,
                                  const QuestWorldView &view) const {
  if (!request.contains("interact_memo") || !objective.contains("memos") ||
      !request_position_matches(request, view.position)) {
    return false;
  }

  const auto &wire = request.at("interact_memo");
  if (wire.value("memo_cms_id", 0) != objective.at("parameters").value("memoId", 0)) {
    return false;
  }
  return placement_nearby(parse_unit_id(wire.at("spot_object_id")), objective.at("memos"), view);
}

int WorldQuestBook::ethereal_amount(const Json &parameters) const {
  const double rate_percent = parameters.value("rate", 100.0);
  const double minimum_value = parameters.value("minValue", 1.0);
  const double maximum_value = parameters.value("maxValue", 1.0);
  // Range-check before narrowing: authored values are small counts.
  if (!std::isfinite(rate_percent) || !(minimum_value >= 0.0) ||
      !(maximum_value >= minimum_value) || maximum_value > kMaximumObjectiveCount) {
    return 0;
  }
  const int minimum = static_cast<int>(minimum_value);
  const int maximum = static_cast<int>(maximum_value);

  std::uniform_real_distribution<double> percent(0.0, 100.0);
  if (rate_percent < 100.0 && percent(random_) >= rate_percent) {
    return 0;
  }
  std::uniform_int_distribution<int> amount(minimum, maximum);
  return amount(random_);
}

QuestResult WorldQuestBook::record_events(const QuestEvents &events, const WorldProgress &current,
                                          const QuestWorldView &view) const {
  QuestResult result;
  if (events.empty()) {
    return result;
  }

  auto next = current;
  // Quests started by a doodad interaction (InteractDoodad acceptance in the authored phase, or
  // a ServerOffered doodad anchor) also count the interaction that started them.
  for (const auto &event : events) {
    if (event.kind == QuestEventKind::DoodadInteracted) {
      start_doodad_quests(event.target_id, event.phase_id, next, view, result.packets);
      offer_quests(OfferTrigger::Doodad, event.target_id, next, view, result.packets);
    }
  }

  const auto before_events = next;
  for (const auto &[quest_id, previous] : before_events.quests) {
    const auto *definition = catalog_->quest(quest_id);
    if (!definition || previous.complete || previous.abandoned) {
      continue;
    }

    auto &quest = next.quests.at(quest_id);
    std::vector<int> changed;
    for (const auto &objective : definition->at("progresses")) {
      // Eligibility comes from the state before these events, as for hunts.
      if (!objective_ready(*definition, previous, objective.at("group"))) {
        continue;
      }

      auto match = match_events(objective, events);
      if (objective.at("kind") == "UseItemInTriggerVolume") {
        // CUSTOM: an unplaced volume (auto_credit) accepts the item use anywhere.
        const bool inside = !objective.contains("trigger") ||
                            position_in_trigger(objective.at("trigger"), view);
        if (inside) {
          match.count = count_events(events, QuestEventKind::ItemUsed,
                                     objective.at("parameters").value("itemId", 0));
        }
      }
      int credit = match.count;
      if (match.ethereal) {
        credit = 0;
        for (int roll = 0; roll < match.count; ++roll) {
          credit += ethereal_amount(objective.at("parameters"));
        }
      }
      if (credit <= 0) {
        continue;
      }
      const int sequence = objective.at("sequence");
      const int required = quest_rules::objective_required_count(objective);
      auto &value = quest.objectives[sequence];
      if (value >= required) {
        continue;
      }
      value = static_cast<int>(std::min<std::int64_t>(required, std::int64_t{value} + credit));
      changed.push_back(sequence);
    }

    for (const int sequence : changed) {
      result.packets.push_back(
          {kQuestUpdate, {{"quest", quest_progress_update_json(quest_id, quest, sequence)}}});
    }
    if (!changed.empty() && definition->at("auto_complete").get<bool>() &&
        reward_supported(*definition) && objectives_complete(*definition, quest)) {
      complete_quest(quest_id, next, view, result.packets);
    }
  }

  if (next == current) {
    return result;
  }
  if (next.revision == std::numeric_limits<std::int64_t>::max()) {
    throw std::runtime_error("World quest event revision exhausted");
  }
  ++next.revision;
  result.next = std::move(next);
  return result;
}

void WorldQuestBook::consume_collected_items(int quest_id, const Json &definition,
                                             WorldProgress &next,
                                             std::vector<GameplayPacket> &packets) const {
  Json stackables = Json::array();
  for (const auto &objective : definition.at("progresses")) {
    if (objective.at("kind") != "GetItem") {
      continue;
    }

    const int item_cms_id = objective.at("parameters").at("itemId");
    const int required = quest_rules::objective_required_count(objective);
    const auto stack = next.stackables.find(item_cms_id);
    if (stack == next.stackables.end()) {
      // Item instances (equipment) are not consumed; storage would need an item trade.
      continue;
    }

    // Only a satisfied objective is turned in; an unmet alternative of its group keeps its items.
    // Utility-bag slots reserve part of a stack, so that part stays.
    const int available = std::max(0, stack->second - reserved_utility_count(next, item_cms_id));
    if (available < required) {
      continue;
    }
    // A depleted stack keeps its row at zero; storage never deletes progress rows.
    stack->second -= required;
    stackables.push_back({{"item_cms_id", item_cms_id}, {"quantity", stack->second}});
  }

  if (stackables.empty()) {
    return;
  }
  packets.push_back({kItemsUpdated,
                     {{"quest_reward", {{"quest_cms_id", quest_id}}},
                      {"stackables", std::move(stackables)}}});
}

bool WorldQuestBook::position_in_trigger(const Json &trigger, const QuestWorldView &view) const {
  // A layered volume (dungeon, channel field) exists only on its own map; others belong to one
  // world asset, whose maps share the coordinates.
  if (trigger.contains("map_id")) {
    if (view.position.map_id != trigger.at("map_id").get<int>()) {
      return false;
    }
  } else if (catalog_->world_of(view.position.map_id) != trigger.at("world").get<std::string>()) {
    return false;
  }
  return position_within_trigger(trigger, view.position, kPositionToleranceMm);
}

bool WorldQuestBook::trigger_matches(const Json &request, const Json &trigger,
                                     const QuestWorldView &view, const char *field) const {
  if (!request.contains(field) || !request_position_matches(request, view.position)) {
    return false;
  }
  const auto &wire = request.at(field);
  if (wire.value("trigger_volume_x", "") != trigger.at("guid").at(0).get<std::string>() ||
      wire.value("trigger_volume_y", "") != trigger.at("guid").at(1).get<std::string>()) {
    return false;
  }
  if (!position_in_trigger(trigger, view)) {
    return false;
  }
  // A leave shares its volume with the enter event but must be reported at the boundary.
  return std::string_view(field) != "trigger_volume_leave" ||
         !position_within_trigger(trigger, view.position, -kPositionToleranceMm);
}

bool WorldQuestBook::conditions_pass(const Json &definition, const WorldProgress &state,
                                     const QuestWorldView &view) const {
  return requirements_met(definition.at("conditions"), state, view);
}

bool WorldQuestBook::requirements_met(const Json &conditions, const WorldProgress &state,
                                      const QuestWorldView &view) const {
  const quest_rules::QuestLookup lookup = [this](int quest_id) { return catalog_->quest(quest_id); };
  const int level = state.level;
  return quest_rules::grouped_conditions_pass(
      conditions, [&](const Json &condition) {
        const auto kind = condition.at("kind").get<std::string>();
        if (kind == "CheckUnitLevel") {
          return level >= condition.at("min").get<int>() && level <= condition.at("max").get<int>();
        }
        if (kind == "Company") {
          return company_requirement_met(condition, view.company);
        }
        if (kind == "OwnItem") {
          return owned_item_count(condition.at("item_id").get<int>(), state, view.character) >=
                 condition.at("count").get<std::int64_t>();
        }
        if (kind == "PlayRecord") {
          return compare_count(play_record_value(condition, state, view.character),
                               condition.at("comparison").get<std::string>(),
                               condition.at("count").get<std::int64_t>());
        }
        if (kind == "AdventureObject") {
          // Candidate: `active` asks whether the object is activated (state 2) or not yet.
          const auto saved =
              state.adventure_objects.find(condition.at("adventure_object_id").get<int>());
          const bool activated = saved != state.adventure_objects.end() && saved->second >= 2;
          return activated == condition.at("active").get<bool>();
        }
        return quest_rules::quest_requirement_met(lookup, condition, state);
      });
}

void WorldQuestBook::require_acceptance_costs(const Json &definition, const WorldProgress &state,
                                              const QuestWorldView &view) const {
  require(state.gold >= definition.value("require_gold", std::int64_t{0}),
          "Quest_IsNotAcceptable_RequireGold");
  for (const auto &item : definition.value("require_items", Json::array())) {
    require(owned_item_count(item.at("item_cms_id").get<int>(), state, view.character) >=
                item.at("quantity").get<std::int64_t>(),
            "Quest_IsNotAcceptable_RequireItemId");
  }
}

bool WorldQuestBook::may_start(int quest_id, const Json &definition, const WorldProgress &state,
                               const QuestWorldView &view) const {
  const auto saved = state.quests.find(quest_id);
  if (saved == state.quests.end() || saved->second.abandoned) {
    return true;
  }
  if (!saved->second.complete) {
    return false;
  }
  // A completed job can be taken again once its board moved to a later refresh period.
  const auto board_id = job_board_of(definition);
  if (!board_id) {
    return false;
  }
  const auto record = state.job_boards.find(*board_id);
  return record == state.job_boards.end() || record->second.day < job_board_period(view);
}

bool WorldQuestBook::acceptance_allowed(const Json &definition, const Json &request,
                                        const WorldProgress &state, const QuestWorldView &view,
                                        std::optional<Json> &npc_position) const {
  const int level = state.level;
  const int quest_id = definition.at("cms_id");
  const bool unit_request =
      request.contains("unit") && request_position_matches(request, view.position);
  const auto requested_unit = [&]() { return parse_unit_id(request.at("unit").at("unit_id")); };

  for (const auto &rule : definition.at("accept")) {
    const auto kind = rule.at("kind").get<std::string>();
    if (kind == "NpcId") {
      if (!unit_request) {
        continue;
      }
      const auto *npc = nearby_npc(requested_unit(), view);
      if (npc && npc->npc_template_id == rule.at("npc_id").get<int>()) {
        npc_position = unit_position_json(npc->position);
        return true;
      }
    } else if (kind == "TriggerVolumeEnter") {
      const auto field = rule.at("request_field").get<std::string>();
      if (trigger_matches(request, rule.at("trigger"), view, field.c_str())) {
        return true;
      }
    } else if (kind == "QuestComplete") {
      const auto *prerequisite = accepted_quest(state, rule.at("quest_id").get<int>());
      if (prerequisite && prerequisite->complete) {
        return true;
      }
    } else if (kind == "CharLevelUp") {
      if (level >= rule.at("min_level").get<int>() && level <= rule.at("max_level").get<int>()) {
        return true;
      }
    } else if (kind == "JobBoard") {
      // Captured client flow (AAC_QuestJobBoard_SendAcceptForBoardUnit): the board widget
      // sends AcceptQuestReq with unit = the board doodad. The quest must be on offer today.
      const int board_id = rule.at("board_id");
      if (unit_request && job_board_nearby(board_id, requested_unit(), view)) {
        const auto offers = job_board_offers(board_id, state, view);
        if (std::ranges::find(offers, quest_id) != offers.end()) {
          return true;
        }
      }
    } else if (kind == "InteractDoodad") {
      if (unit_request && doodad_matches(requested_unit(), rule.at("doodads"),
                                         rule.at("target_phase").get<int>(), view)) {
        return true;
      }
    } else if (kind == "InteractMemo") {
      if (unit_request && placement_nearby(requested_unit(), rule.at("memos"), view)) {
        return true;
      }
    }
    // "Sequential" quests are accepted only by their predecessor's completion, "ServerOffered"
    // quests only by the server and "GmOnly" quests only by a game master.
  }
  return false;
}

std::vector<int> WorldQuestBook::refresh_state_objectives(const Json &definition,
                                                          QuestProgress &quest,
                                                          const WorldProgress &state,
                                                          const QuestWorldView &view,
                                                          bool gathered_items_only) const {
  std::vector<int> changed;
  for (const auto &objective : definition.at("progresses")) {
    if (!objective_ready(definition, quest, objective.at("group"))) {
      continue;
    }

    const auto kind = objective.at("kind").get<std::string>();
    if (gathered_items_only && kind != "GetItem") {
      continue;
    }
    const auto &parameters = objective.at("parameters");
    const int required = quest_rules::objective_required_count(objective);
    std::int64_t observed = -1;
    if (objective.value("auto_credit", false)) {
      // CUSTOM: the step names a volume or memo this client build never placed.
      observed = required;
    } else if (kind == "GetItem") {
      observed = owned_item_count(parameters.at("itemId").get<int>(), state, view.character);
    } else if (kind == "CharLevelUp") {
      observed = state.level >= parameters.at("level").get<int>() ? required : 0;
    } else if (kind == "EquipItem") {
      observed = item_equipped(parameters.at("itemId").get<int>(), view.character) ? required : 0;
    } else if (kind == "AdventureObjectStatus") {
      const auto saved = state.adventure_objects.find(parameters.at("adventureObjectId").get<int>());
      const int wanted =
          parameters.at("state") == "EX5AdventureObjectState_Activated" ? 2 : 1;
      observed = saved != state.adventure_objects.end() && saved->second >= wanted ? required : 0;
    } else if (kind == "CompanyContributionTotal") {
      observed = view.company ? view.company->contribution : 0;
    } else if (kind == "housingFunishing") {
      observed = housing_furniture_installed(state) ? required : 0;
    } else if (kind == "CheckHp") {
      // The player's health has dropped to the authored ratio or below.
      observed = view.hp_percent && *view.hp_percent <= parameters.value("hpRate", 0) ? required
                                                                                       : 0;
    } else if (kind == "TimeElapsed") {
      const auto elapsed_ms = view.now_epoch_ms - quest.started_epoch_ms;
      observed = quest.started_epoch_ms > 0 && elapsed_ms >= parameters.value("time", 0)
                     ? required
                     : 0;
    }
    if (observed < 0) {
      continue;
    }

    const int sequence = objective.at("sequence");
    auto &value = quest.objectives[sequence];
    const int capped = static_cast<int>(std::min<std::int64_t>(observed, required));
    // Saved objective counters never decrease (storage invariant).
    if (capped > value) {
      value = capped;
      changed.push_back(sequence);
    }
  }
  return changed;
}

void WorldQuestBook::refresh_active_quests(WorldProgress &next, const QuestWorldView &view,
                                           std::vector<GameplayPacket> &packets,
                                           bool gathered_items_only) const {
  for (const int quest_id : active_quest_ids(next)) {
    const auto *definition = catalog_->quest(quest_id);
    if (!definition) {
      continue;
    }
    auto &quest = next.quests.at(quest_id);
    // Sequential groups can unlock further state objectives, so repeat until stable.
    std::vector<int> changed;
    for (std::size_t pass = 0; pass < kMaximumObjectives; ++pass) {
      const auto step = refresh_state_objectives(*definition, quest, next, view,
                                                  gathered_items_only);
      if (step.empty()) {
        break;
      }
      changed.insert(changed.end(), step.begin(), step.end());
    }
    for (const int sequence : changed) {
      packets.push_back(
          {kQuestUpdate, {{"quest", quest_progress_update_json(quest_id, quest, sequence)}}});
    }
    if (!changed.empty() && definition->at("auto_complete").get<bool>() &&
        reward_supported(*definition) && objectives_complete(*definition, quest)) {
      complete_quest(quest_id, next, view, packets);
    }
  }
}

void WorldQuestBook::offer_quests(OfferTrigger trigger, int target_id, WorldProgress &next,
                                  const QuestWorldView &view,
                                  std::vector<GameplayPacket> &packets,
                                  const std::set<int> *allowed_quest_ids) const {
  for (const int quest_id : catalog_->offered_quest_ids()) {
    if (allowed_quest_ids && !allowed_quest_ids->contains(quest_id)) {
      continue;
    }
    const auto &definition = *catalog_->quest(quest_id);
    const auto rule = std::ranges::find_if(definition.at("accept"), [](const Json &entry) {
      return entry.at("kind") == "ServerOffered";
    });
    const auto contains = [&](const char *field) {
      return std::ranges::any_of(rule->at(field), [target_id](const Json &value) {
        return value.get<int>() == target_id;
      });
    };

    bool triggered = false;
    switch (trigger) {
    case OfferTrigger::Npc:
      triggered = contains("npc_ids");
      break;
    case OfferTrigger::Monster:
      triggered = contains("monster_ids");
      break;
    case OfferTrigger::Doodad:
      triggered = contains("doodad_ids");
      break;
    case OfferTrigger::Map: {
      // Map offers apply to quests without an NPC, monster or doodad anchor, once: a quest the
      // player abandoned is not forced back on the next map change.
      const bool anchored = !rule->at("npc_ids").empty() || !rule->at("monster_ids").empty() ||
                            !rule->at("doodad_ids").empty();
      const auto &maps = rule->at("zone_maps");
      const bool on_map = maps.empty() || std::ranges::any_of(maps, [&](const Json &map_id) {
                            return map_id.get<int>() == view.position.map_id;
                          });
      const auto after = rule->value("after_quest_id", 0);
      const auto *predecessor = after > 0 ? accepted_quest(next, after) : nullptr;
      const bool predecessor_done = after == 0 || (predecessor && predecessor->complete);
      triggered = !anchored && on_map && predecessor_done && !next.quests.contains(quest_id);
      break;
    }
    }
    if (!triggered) {
      continue;
    }
    try_begin(quest_id, next, view, packets);
  }
}

bool WorldQuestBook::try_begin(int quest_id, WorldProgress &next, const QuestWorldView &view,
                               std::vector<GameplayPacket> &packets) const {
  const auto &definition = *catalog_->quest(quest_id);
  if (!may_start(quest_id, definition, next, view) || !conditions_pass(definition, next, view)) {
    return false;
  }

  // A quest whose costs or supplies cannot be met is skipped without partial changes.
  auto attempt = next;
  std::vector<GameplayPacket> started;
  try {
    require_acceptance_costs(definition, attempt, view);
    begin_quest(quest_id, attempt, view, started, std::nullopt);
  } catch (const RuleError &) {
    return false;
  }
  next = std::move(attempt);
  packets.insert(packets.end(), std::make_move_iterator(started.begin()),
                 std::make_move_iterator(started.end()));
  return true;
}

void WorldQuestBook::start_doodad_quests(int doodad_id, int phase_id, WorldProgress &next,
                                         const QuestWorldView &view,
                                         std::vector<GameplayPacket> &packets) const {
  for (const int quest_id : catalog_->doodad_accept_quests(doodad_id)) {
    const auto &definition = *catalog_->quest(quest_id);
    const bool in_phase = std::ranges::any_of(definition.at("accept"), [&](const Json &rule) {
      const int target_phase = rule.value("target_phase", 0);
      return rule.at("kind") == "InteractDoodad" && rule.at("doodad_id") == doodad_id &&
             (target_phase == 0 || target_phase == phase_id);
    });
    if (in_phase) {
      try_begin(quest_id, next, view, packets);
    }
  }
}

void WorldQuestBook::begin_quest(int quest_id, WorldProgress &next, const QuestWorldView &view,
                                 std::vector<GameplayPacket> &packets,
                                 const std::optional<Json> &npc_position) const {
  const auto &definition = *catalog_->quest(quest_id);

  QuestProgress quest;
  const auto previous = next.quests.find(quest_id);
  const bool restart = previous != next.quests.end();
  if (restart) {
    // An abandoned or repeated quest keeps its success count and starts a new attempt.
    quest.attempt = previous->second.attempt + 1;
    quest.success_count = previous->second.success_count;
  } else {
    require(next.quests.size() < kMaximumSavedQuests, "BadRequest");
  }
  quest.started_epoch_ms = view.now_epoch_ms;
  for (const auto &objective : definition.at("progresses")) {
    quest.objectives.emplace(objective.at("sequence").get<int>(), 0);
  }

  // A restarted quest tops supplies up to the supplied amount instead of duplicating them.
  Json supplies = Json::array();
  for (const auto &supply : definition.at("supplies")) {
    const int item_cms_id = supply.at("item_cms_id");
    const auto owned = restart ? owned_item_count(item_cms_id, next, view.character) : 0;
    const auto missing = supply.at("quantity").get<std::int64_t>() - owned;
    if (missing > 0) {
      supplies.push_back({{"item_cms_id", item_cms_id}, {"quantity", missing}});
    }
  }
  if (!supplies.empty()) {
    quest_rules::grant_rewards(next, supplies, packets, "quest");
  }
  refresh_state_objectives(definition, quest, next, view);
  next.quests.insert_or_assign(quest_id, quest);

  Json accepted{{"quest", quest_json(quest_id, quest)}};
  if (npc_position) {
    accepted["npc_pos"] = *npc_position;
  }
  packets.push_back({kQuestAccepted, std::move(accepted)});

  if (definition.at("auto_complete").get<bool>() && reward_supported(definition) &&
      objectives_complete(definition, quest)) {
    complete_quest(quest_id, next, view, packets);
  }
}

void WorldQuestBook::credit_gain_objectives(const char *kind, std::int64_t amount,
                                            WorldProgress &next,
                                            std::vector<GameplayPacket> &packets) const {
  if (amount <= 0) {
    return;
  }
  for (auto &[quest_id, quest] : next.quests) {
    const auto *definition = catalog_->quest(quest_id);
    if (!definition || quest.complete || quest.abandoned) {
      continue;
    }
    for (const auto &objective : definition->at("progresses")) {
      if (objective.at("kind") != kind ||
          !objective_ready(*definition, quest, objective.at("group"))) {
        continue;
      }
      const int sequence = objective.at("sequence");
      const int required = quest_rules::objective_required_count(objective);
      auto &value = quest.objectives[sequence];
      if (value >= required) {
        continue;
      }
      value = static_cast<int>(std::min<std::int64_t>(required, value + amount));
      packets.push_back(
          {kQuestUpdate, {{"quest", quest_progress_update_json(quest_id, quest, sequence)}}});
    }
  }
}

void WorldQuestBook::grant_quest_experience(std::int64_t catalog_experience, WorldProgress &next,
                                            std::vector<GameplayPacket> &packets) const {
  const auto before = next.experience;
  quest_rules::grant_experience(next, catalog_experience, packets, progression_.get());
  // LevelExpGain counts the EXP the server granted after the quest was accepted.
  credit_gain_objectives("LevelExpGain", next.experience - before, next, packets);
}

void WorldQuestBook::grant_extra_rewards(const Json &definition, WorldProgress &next,
                                         std::vector<GameplayPacket> &packets) const {
  // Randomly rolled LootPack rewards: the pack rate, then each group's rate, then one
  // weighted item per group with a uniform amount (the gathering loot convention).
  Json rolled = Json::array();
  std::uniform_real_distribution<double> percent(0.0, 100.0);
  for (const auto &pack : definition.value("loot_packs", Json::array())) {
    if (percent(random_) >= pack.at("pack_rate_percent").get<double>()) {
      continue;
    }
    for (const auto &group : pack.at("groups")) {
      if (percent(random_) >= group.at("rate_percent").get<double>()) {
        continue;
      }
      std::vector<int> weights;
      for (const auto &item : group.at("items")) {
        weights.push_back(item.at("weight").get<int>());
      }
      std::discrete_distribution<std::size_t> choose(weights.begin(), weights.end());
      const auto &item = group.at("items").at(choose(random_));
      std::uniform_int_distribution<int> amount(item.at("min_quantity").get<int>(),
                                                item.at("max_quantity").get<int>());
      Json entry{{"item_cms_id", item.at("item_cms_id")}, {"quantity", amount(random_)}};
      if (item.contains("money_type")) {
        entry["money_type"] = item.at("money_type");
      }
      rolled.push_back(std::move(entry));
    }
  }
  if (!rolled.empty()) {
    quest_rules::grant_rewards(next, rolled, packets, "quest_reward");
  }

  for (const auto &points : definition.value("build_points", Json::array())) {
    if (!progression_) {
      continue;
    }
    const bool weapon = points.at("type") == "WeaponPoint";
    const auto error = progression_->grant_build_points(
        next, weapon ? kWeaponPointType : kLevelUpPointType, points.at("value").get<int>());
    require(error == x5::ec::Success, "Quest_RewardFailed");
    packets.push_back({quest_rules::kCharacterBaseChangedOpcode,
                       weapon ? weapon_points_message(next) : level_up_points_message(next)});
  }

  for (const auto &mate : definition.value("mates", Json::array())) {
    const int mate_id = mate.get<int>();
    if (next.mates.contains(mate_id)) {
      continue;
    }
    next.mates.emplace(mate_id, MateRecord{});
    packets.push_back({kRegisterMateNpc, {{"mate_npc_cms_id", mate_id}}});
  }

  for (const auto &gain : definition.value("mate_intimacy", Json::array())) {
    // Intimacy only grows for a registered mate, up to the companion service's ceiling.
    const auto mate = next.mates.find(gain.at("mate_id").get<int>());
    if (mate == next.mates.end()) {
      continue;
    }
    const auto limit = gain.value("limit", std::numeric_limits<int>::max());
    auto &intimacy = mate->second.intimacy;
    intimacy = static_cast<int>(std::min<std::int64_t>(
        static_cast<std::int64_t>(intimacy) + gain.at("amount").get<int>(), limit));
    packets.push_back(
        {kChangedMateIntimacy, {{"mate_npc_cms_id", mate->first}, {"result_intimate", intimacy}}});
  }
}

void WorldQuestBook::complete_quest(int quest_id, WorldProgress &next, const QuestWorldView &view,
                                    std::vector<GameplayPacket> &packets) const {
  const auto &definition = *catalog_->quest(quest_id);
  auto &quest = next.quests.at(quest_id);
  quest.complete = true;
  quest.success_count += 1;
  quest_rules::grant_rewards(next, definition.at("rewards"), packets, "quest_reward");
  grant_extra_rewards(definition, next, packets);
  grant_quest_experience(definition.at("experience").get<std::int64_t>(), next, packets);
  packets.push_back({kQuestUpdate, {{"quest", quest_json(quest_id, next.quests.at(quest_id))}}});

  // CompanyContributionGain counts the contribution quest completions credit to the character's
  // company; the company service applies the points after this commit.
  const auto contribution = definition.value("company_contribution", std::int64_t{0});
  if (view.company && view.company->company_type != 0) {
    credit_gain_objectives("CompanyContributionGain", contribution, next, packets);
  }

  start_story_followups(next, view, packets);

  // A sequential successor is accepted by the server; others wait for their own trigger.
  if (!definition.contains("next_quest")) {
    return;
  }
  const int successor_id = definition.at("next_quest");
  const auto &successor = *catalog_->quest(successor_id);
  const auto &rules = successor.at("accept");
  const bool sequential =
      rules.empty() || std::ranges::any_of(rules, [](const Json &rule) {
        return rule.at("kind") == "Sequential";
      });
  if (sequential && !accepted_quest(next, successor_id) && acceptance_supported(successor)) {
    begin_quest(successor_id, next, view, packets, std::nullopt);
  }
}

void WorldQuestBook::start_story_followups(
    WorldProgress &next, const QuestWorldView &view, std::vector<GameplayPacket> &packets) const {
  // The first four transitions were observed in P2. The remaining transitions follow
  // authored QuestComplete acceptance rules; their automatic timing is a candidate.
  // Periodic refresh also repairs characters stranded by the missing transitions.
  constexpr std::array<std::pair<int, int>, 7> followups{{{20001052, 20001053},
                                                          {20001053, 20001054},
                                                          {20001054, 10000146},
                                                          {10000146, 10000133},
                                                          {10000133, 10000180},
                                                          {10000149, 80101030},
                                                          {80101030, 10000118}}};
  for (const auto &[predecessor_id, successor_id] : followups) {
    const auto predecessor = next.quests.find(predecessor_id);
    const auto *successor = catalog_->quest(successor_id);
    if (predecessor == next.quests.end() || !predecessor->second.complete ||
        predecessor->second.abandoned || !successor || next.quests.contains(successor_id)) {
      continue;
    }

    const auto &rules = successor->at("accept");
    const auto *previous_definition = catalog_->quest(predecessor_id);
    const bool quest_complete_rule = std::ranges::any_of(rules, [&](const Json &rule) {
      return rule.value("kind", std::string{}) == "QuestComplete" &&
             rule.value("quest_id", 0) == predecessor_id;
    });
    const bool sequential_rule = rules.size() == 1 &&
                                 rules[0].value("kind", std::string{}) == "Sequential" &&
                                 previous_definition &&
                                 previous_definition->value("next_quest", 0) == successor_id;
    if ((!quest_complete_rule && !sequential_rule) ||
        successor->value("require_gold", 0) != 0 || !successor->at("require_items").empty() ||
        !acceptance_supported(*successor) || !conditions_pass(*successor, next, view) ||
        !may_start(successor_id, *successor, next, view)) {
      continue;
    }
    begin_quest(successor_id, next, view, packets, std::nullopt);
  }
}

void WorldQuestBook::accept(const Json &request, WorldProgress &next, const QuestWorldView &view,
                            std::vector<GameplayPacket> &packets) const {
  const int quest_id = request.at("quest_cms_id");
  const auto *definition = catalog_->quest(quest_id);
  require(definition != nullptr, "Quest_InvalidCmsId");

  if (!may_start(quest_id, *definition, next, view)) {
    // Repeated acceptance never restarts a quest or grants its supplies again.
    const auto &saved = next.quests.at(quest_id);
    const auto opcode = saved.complete ? kQuestUpdate : kQuestAccepted;
    packets.push_back({opcode, {{"quest", quest_json(quest_id, saved)}}});
    return;
  }

  std::optional<Json> npc_position;
  require(acceptance_supported(*definition) && conditions_pass(*definition, next, view),
          "Quest_IsNotAcceptable");
  require_acceptance_costs(*definition, next, view);
  require(acceptance_allowed(*definition, request, next, view, npc_position),
          "Quest_IsNotAcceptable");

  const auto board_id = job_board_of(*definition);
  if (board_id) {
    // A repeated job's completed record becomes a tombstone before the new attempt.
    renew_job_board(*board_id, next, packets, view);
  }
  begin_quest(quest_id, next, view, packets, npc_position);
}

void WorldQuestBook::progress(const Json &request, WorldProgress &next, const QuestWorldView &view,
                              std::vector<GameplayPacket> &packets) const {
  const int quest_id = request.at("quest_cms_id");
  const int sequence_id = request.at("quest_progress_sequence_id");
  const auto *definition = catalog_->quest(quest_id);
  require(definition != nullptr && accepted_quest(next, quest_id), "Quest_IsNotInProgress");
  auto &quest = next.quests.at(quest_id);
  if (quest.complete) {
    packets.push_back({kQuestUpdate, {{"quest", quest_json(quest_id, quest)}}});
    return;
  }

  const auto &objectives = definition->at("progresses");
  const auto objective = std::ranges::find_if(objectives, [sequence_id](const Json &entry) {
    return entry.at("sequence") == sequence_id;
  });
  require(objective != objectives.end(), "Quest_IsNotProgress");
  require(objective_ready(*definition, quest, objective->at("group")), "Quest_IsNotProgress");

  const auto kind = objective->at("kind").get<std::string>();
  if ((kind == "TriggerVolumeEnter" || kind == "TriggerVolumeLeave") &&
      objective->contains("trigger")) {
    const char *field =
        kind == "TriggerVolumeLeave" ? "trigger_volume_leave" : "trigger_volume_enter";
    require(trigger_matches(request, objective->at("trigger"), view, field),
            "Quest_IsNotProgress");
    quest.objectives[sequence_id] = quest_rules::objective_required_count(*objective);
  } else if (kind == "DialogueSelection") {
    const auto &parameters = objective->at("parameters");
    const auto &selection = request.at("dialogue_selection");
    require(dialogue_target_.has_value() &&
                parse_unit_id(selection.at("unit_id")) == *dialogue_target_ &&
                request_position_matches(request, view.position),
            "Quest_IsNotProgress");
    const auto *npc = nearby_npc(*dialogue_target_, view);
    require(npc && npc->npc_template_id == parameters.at("targetId").get<int>() &&
                selection.at("dialogue_cms_id") == parameters.at("dialogueId") &&
                selection.at("sequence_order") == parameters.at("sequenceOrder") &&
                selection.at("select_order") == parameters.at("selectOrder"),
            "Quest_IsNotProgress");
    quest.objectives[sequence_id] = quest_rules::objective_required_count(*objective);
  } else if (kind == "InteractMemo" && objective->contains("memos")) {
    // Captured: the client reports reading a placed board with interact_memo{memo_cms_id,
    // spot_object_id}; the official server answered with the objective's QuestUpdateNoti.
    require(memo_matches(request, *objective, view), "Quest_IsNotProgress");
    quest.objectives[sequence_id] = quest_rules::objective_required_count(*objective);
  } else if (kind == "InteractNpc") {
    // Captured: after DialogueStartReq the client reports interact_npc{npc_unit_id}. The dialogue
    // start may already have credited it, so a repeated valid report confirms the same value.
    require(request.contains("interact_npc") && request_position_matches(request, view.position),
            "Quest_IsNotProgress");
    const auto *npc = nearby_npc(parse_unit_id(request.at("interact_npc").at("npc_unit_id")), view);
    require(npc && npc->npc_template_id == objective->at("parameters").at("npcId").get<int>(),
            "Quest_IsNotProgress");
  } else if (kind == "AdventureLogbookPercentage") {
    // CUSTOM: the adventure logbook percentage is computed by the client from the zone's
    // logbook entries; the server has no recovered formula, so it accepts the report for the
    // objective's zone when it reaches the authored percentage.
    require(request.contains("adventure_logbook_percentage"), "Quest_IsNotProgress");
    const auto &report = request.at("adventure_logbook_percentage");
    const auto &parameters = objective->at("parameters");
    require(report.value("zone_key", "") == parameters.value("zoneKey", "") &&
                report.value("percentage", 0) >= parameters.value("percentage", 0),
            "Quest_IsNotProgress");
    quest.objectives[sequence_id] = quest_rules::objective_required_count(*objective);
  } else {
    // Item, level, equipment, adventure, company, housing, health and time objectives follow
    // server state, and unplaced steps are credited by the server; kills, doodads, item uses
    // and skills are server events. A client report (time, contribution, housing furniture,
    // EXP gain) only asks for a re-evaluation.
    const auto changed = refresh_state_objectives(*definition, quest, next, view);
    require(std::ranges::find(changed, sequence_id) != changed.end(), "Quest_IsNotProgress");
  }

  packets.push_back(
      {kQuestUpdate, {{"quest", quest_progress_update_json(quest_id, quest, sequence_id)}}});
  if (definition->at("auto_complete").get<bool>() && reward_supported(*definition) &&
      objectives_complete(*definition, quest)) {
    complete_quest(quest_id, next, view, packets);
  }
}

void WorldQuestBook::reward(const Json &request, WorldProgress &next, const QuestWorldView &view,
                            std::vector<GameplayPacket> &packets) const {
  const int quest_id = request.at("quest_cms_id");
  const auto *definition = catalog_->quest(quest_id);
  require(definition != nullptr && accepted_quest(next, quest_id), "Quest_IsNotInProgress");
  if (next.quests.at(quest_id).complete) {
    packets.push_back({kQuestUpdate, {{"quest", quest_json(quest_id, next.quests.at(quest_id))}}});
    return;
  }
  require(reward_supported(*definition), "Quest_IsNotComplete");

  std::optional<std::uint64_t> request_unit;
  if (request.contains("unit_id") && request.at("unit_id") != "0" &&
      request.at("unit_id") != 0) {
    request_unit = parse_unit_id(request.at("unit_id"));
  }

  const auto &completion = definition->at("completion");
  const auto completion_kind = completion.at("kind").get<std::string>();
  if (completion_kind == "Npc") {
    // The turn-in NPC is the request's unit or the open dialogue's NPC.
    const auto unit_id = request_unit ? request_unit : dialogue_target_;
    const auto *npc = unit_id ? nearby_npc(*unit_id, view) : nullptr;
    require(npc && std::ranges::any_of(completion.at("npc_ids"),
                                       [npc](const Json &npc_id) {
                                         return npc_id.get<int>() == npc->npc_template_id;
                                       }),
            "Quest_IsNotComplete");
  } else if (completion_kind == "JobBoard") {
    // Captured client flow (AAC_Quest_SendQuestRewardReqForUnit): the turn-in names the board.
    const int board_id = completion.at("board_id");
    require(request_unit && job_board_nearby(board_id, *request_unit, view),
            "Quest_IsNotComplete");
    renew_job_board(board_id, next, packets, view);
  } else if (completion_kind == "Doodad") {
    require(request_unit && doodad_matches(*request_unit, completion.at("doodads"),
                                           completion.at("target_phase").get<int>(), view),
            "Quest_IsNotComplete");
  }

  auto &quest = next.quests.at(quest_id);
  refresh_state_objectives(*definition, quest, next, view);
  require(objectives_complete(*definition, quest), "Quest_IsNotComplete");
  // Possession objectives must still hold at turn-in, not only when they were recorded.
  for (const auto &objective : definition->at("progresses")) {
    if (objective.at("kind") != "GetItem") {
      continue;
    }
    const int item_id = objective.at("parameters").at("itemId");
    require(owned_item_count(item_id, next, view.character) >=
                quest_rules::objective_required_count(objective),
            "Quest_IsNotComplete");
  }
  consume_collected_items(quest_id, *definition, next, packets);
  complete_quest(quest_id, next, view, packets);
}

void WorldQuestBook::abandon(const Json &request, WorldProgress &next,
                             std::vector<GameplayPacket> &packets) const {
  const int quest_id = request.at("quest_cms_id");
  const auto *definition = catalog_->quest(quest_id);
  const auto *saved = accepted_quest(next, quest_id);
  require(definition != nullptr && saved != nullptr, "Quest_IsNotInProgress");
  require(!saved->complete && definition->value("abandonable", true), "Quest_AbandonFailed");

  // The record stays as a tombstone of a finished attempt (rows are never deleted); a later
  // acceptance starts the next attempt from empty progress.
  QuestProgress tombstone;
  tombstone.attempt = saved->attempt + 1;
  tombstone.success_count = saved->success_count;
  tombstone.abandoned = true;
  for (const auto &[sequence, value] : saved->objectives) {
    tombstone.objectives.emplace(sequence, 0);
  }
  next.quests.insert_or_assign(quest_id, tombstone);
  packets.push_back({kQuestAbandoned, {{"quest_cms_id", quest_id}, {"force", false}}});
}

void WorldQuestBook::start_dialogue(const Json &request, WorldProgress &next,
                                    const QuestWorldView &view,
                                    std::vector<GameplayPacket> &packets) {
  const auto unit_id = parse_unit_id(request.at("target_unit_id"));
  require(request_position_matches(request, view.position), "TooFar");
  const auto *npc = nearby_npc(unit_id, view);
  require(npc != nullptr, "Interaction_TargetNotFound");
  dialogue_target_ = unit_id;
  dialogue_npc_template_id_ = npc->npc_template_id;

  const auto npc_position = unit_position_json(npc->position);
  packets.push_back({kUnitInteracted,
                     {{"interacter_unit_id", std::to_string(player_unit_id_)},
                      {"unit_id", std::to_string(unit_id)},
                      {"pos", npc_position}}});
  packets.push_back({kDialogueStarted,
                     {{"target_unit_id", std::to_string(unit_id)},
                      {"target_unit_pos", npc_position}}});

  // A ServerOffered quest anchored on this NPC starts with the conversation.
  offer_quests(OfferTrigger::Npc, npc->npc_template_id, next, view, packets);

  // Talking to an NPC credits ready InteractNpc objectives for that NPC template.
  for (auto &[quest_id, quest] : next.quests) {
    const auto *definition = catalog_->quest(quest_id);
    if (!definition || quest.complete || quest.abandoned) {
      continue;
    }
    for (const auto &objective : definition->at("progresses")) {
      if (objective.at("kind") != "InteractNpc" ||
          objective.at("parameters").at("npcId").get<int>() != npc->npc_template_id ||
          !objective_ready(*definition, quest, objective.at("group"))) {
        continue;
      }
      const int sequence = objective.at("sequence");
      auto &value = quest.objectives[sequence];
      if (value >= quest_rules::objective_required_count(objective)) {
        continue;
      }
      ++value;
      packets.push_back(
          {kQuestUpdate, {{"quest", quest_progress_update_json(quest_id, quest, sequence)}}});
    }
  }
}

