// Unsupported reasons are "<category>:<detail>" strings written by the catalog generator.
bool has_unsupported(const Json &definition, std::string_view category) {
  for (const auto &reason : definition.at("unsupported")) {
    const auto text = reason.get<std::string>();
    if (text.starts_with(category) && text.size() > category.size() &&
        text[category.size()] == ':') {
      return true;
    }
  }
  return false;
}

bool acceptance_supported(const Json &definition) {
  return !has_unsupported(definition, "accept") && !has_unsupported(definition, "condition") &&
         !has_unsupported(definition, "requirement") && !has_unsupported(definition, "supply");
}

// Only an unmodeled completion mechanic blocks the reward; a catalog generated by this build
// models every completion kind.
bool reward_supported(const Json &definition) {
  return !has_unsupported(definition, "completion");
}

// RequirementType.Company, checked in the client's order
// (AAC_Requirement_CheckCompany_Candidate): same company, a valid pioneer permit unless the
// condition ignores it, the minimum position level, the capped-level ceiling when
// is_max_contribution is set, and the minimum contribution. Without a company service the
// standing is unknown and the condition fails closed.
bool company_requirement_met(const Json &condition,
                             const std::optional<QuestCompanyStanding> &standing) {
  if (!standing || standing->company_type != condition.at("company_type").get<int>()) {
    return false;
  }
  if (!condition.at("ignore_permit").get<bool>() && !standing->pioneer_permit_valid) {
    return false;
  }
  if (standing->position_level < condition.at("level").get<int>()) {
    return false;
  }
  if (condition.at("is_max_contribution").get<bool>() && !standing->at_capped_level_ceiling) {
    return false;
  }
  return standing->contribution >= condition.at("contribution").get<std::int64_t>();
}

std::vector<QuestCompanyUnlock> company_unlocks_of(const Json &definition) {
  std::vector<QuestCompanyUnlock> unlocks;
  if (!definition.contains("company_unlocks")) {
    return unlocks;
  }
  for (const auto &unlock : definition.at("company_unlocks")) {
    unlocks.push_back({unlock.at("company_type").get<int>(), unlock.at("level").get<int>()});
  }
  return unlocks;
}

// True when `after` holds a completion of the quest that `before` did not: a first completion,
// or the completion of a later attempt of a repeated job.
bool newly_completed(const WorldProgress &before, int quest_id, const QuestProgress &after) {
  if (!after.complete) {
    return false;
  }
  const auto previous = before.quests.find(quest_id);
  return previous == before.quests.end() || !previous->second.complete ||
         previous->second.attempt != after.attempt;
}

std::int64_t owned_item_count(int item_cms_id, const WorldProgress &state,
                              const Character *character) {
  std::int64_t owned = 0;
  const auto stack = state.stackables.find(item_cms_id);
  if (stack != state.stackables.end()) {
    owned += stack->second;
  }
  if (character) {
    for (const auto &item : character->items) {
      if (item.cms_id == item_cms_id) {
        owned += item.quantity;
      }
    }
  }
  return owned;
}

bool item_equipped(int item_cms_id, const Character *character) {
  if (!character) {
    return false;
  }
  return std::ranges::any_of(character->items, [item_cms_id](const CharacterItem &item) {
    return item.cms_id == item_cms_id && item.equip_slot.has_value();
  });
}

bool compare_count(std::int64_t value, const std::string &comparison, std::int64_t expected) {
  if (comparison == "Equal") {
    return value == expected;
  }
  if (comparison == "NotEqual") {
    return value != expected;
  }
  if (comparison == "GreaterThan") {
    return value > expected;
  }
  if (comparison == "LessThan") {
    return value < expected;
  }
  if (comparison == "LessThanOrEqual") {
    return value <= expected;
  }
  return value >= expected;
}

// PlayRecord condition value: tracked kill counters, or for GetItem records the larger of the
// counter and the current holdings (acquisitions are not counted separately).
std::int64_t play_record_value(const Json &condition, const WorldProgress &state,
                               const Character *character) {
  const int record_id = condition.at("play_record_id");
  const auto saved = state.play_records.find(record_id);
  const std::int64_t counted = saved == state.play_records.end() ? 0 : saved->second;
  const auto &record = condition.at("record");
  if (record.at("kind") == "GetItem") {
    return std::max(counted,
                    owned_item_count(record.at("item_id").get<int>(), state, character));
  }
  return counted;
}

bool housing_furniture_installed(const WorldProgress &state) {
  return std::ranges::any_of(state.housing_items, [](const auto &entry) {
    return entry.second.installed_count > 0;
  });
}

// The events a simple counter objective receives. Ethereal objectives roll a virtual amount
// per event. UseItemInTriggerVolume also needs the player position and is matched by the book.
struct EventMatch {
  int count{};
  bool ethereal{};
};

int count_events(const QuestEvents &events, QuestEventKind kind, int target_id,
                 int context_id = 0) {
  int count = 0;
  for (const auto &event : events) {
    if (event.kind == kind && event.target_id == target_id &&
        (context_id == 0 || event.context_id == context_id)) {
      count += event.count;
    }
  }
  return count;
}

EventMatch match_events(const Json &objective, const QuestEvents &events) {
  const auto kind = objective.at("kind").get<std::string>();
  const auto &parameters = objective.at("parameters");
  EventMatch match;
  if (kind == "CounterSuccessCrafting" || kind == "CounterTryCrafting") {
    // Every server craft that commits succeeded, so it is also an attempt.
    match.count =
        count_events(events, QuestEventKind::CraftSucceeded, parameters.value("craftId", 0));
  } else if (kind == "InteractDoodad" || kind == "EtherealInteractDoodad") {
    const int doodad_id = parameters.value("doodadId", 0);
    const int target_phase = parameters.value("targetPhase", 0);
    for (const auto &event : events) {
      if (event.kind == QuestEventKind::DoodadInteracted && event.target_id == doodad_id &&
          (target_phase == 0 || event.phase_id == target_phase)) {
        match.count += event.count;
      }
    }
    match.ethereal = kind == "EtherealInteractDoodad";
  } else if (kind == "CounterUseItem") {
    match.count = count_events(events, QuestEventKind::ItemUsed, parameters.value("itemId", 0));
  } else if (kind == "TradePayment") {
    match.count = count_events(events, QuestEventKind::TradeGoodSold,
                               parameters.value("tradeGoodId", 0),
                               parameters.value("tradingPostId", 0));
  } else if (kind == "CounterUseSkill") {
    match.count = count_events(events, QuestEventKind::SkillUsed, parameters.value("skillId", 0));
  } else if (kind == "CounterUseSkillEffect") {
    match.count = count_events(events, QuestEventKind::SkillEffectExecuted,
                               parameters.value("skillEffectId", 0));
  } else if (kind == "AddStatusEffect") {
    match.count = count_events(events, QuestEventKind::StatusEffectApplied,
                               parameters.value("statusEffectId", 0));
  } else if (kind == "DestroyObject") {
    match.count = count_events(events, QuestEventKind::ObjectDestroyed,
                               parameters.value("destructibleObjectId", 0));
  }
  return match;
}

bool hunts_monster(const Json &objective, int npc_cms_id) {
  const auto kind = objective.at("kind").get<std::string>();
  if (kind != "HuntMonster" && kind != "EtherealHuntMonster") {
    return false;
  }
  if (objective.at("parameters").value("npcId", 0) == npc_cms_id) {
    return true;
  }
  // Hunts naming a list of templates (npcIds) or an NpcGroup credit any of them.
  if (!objective.contains("npc_ids")) {
    return false;
  }
  return std::ranges::any_of(objective.at("npc_ids"), [npc_cms_id](const Json &npc_id) {
    return npc_id.get<int>() == npc_cms_id;
  });
}

void validate_placements(const Json &placements) {
  if (!placements.is_array()) {
    throw std::runtime_error("Invalid quest catalog placements");
  }
  for (const auto &placement : placements) {
    if (placement.at("world").get<std::string>().empty() ||
        !placement.at("unit_id").is_string() || !placement.at("center").is_array() ||
        placement.at("center").size() != 3) {
      throw std::runtime_error("Invalid quest catalog placement");
    }
  }
}

void validate_trigger_definition(const Json &trigger) {
  const auto &guid = trigger.at("guid");
  if (!guid.is_array() || guid.size() != 2 || !trigger.at("center").is_array() ||
      trigger.at("center").size() != 3 || trigger.at("world").get<std::string>().empty() ||
      (trigger.contains("map_id") && trigger.at("map_id").get<int>() <= 0)) {
    throw std::runtime_error("Invalid quest catalog trigger");
  }
  if (trigger.contains("radius")) {
    if (trigger.at("radius").get<int>() <= 0) {
      throw std::runtime_error("Invalid quest catalog trigger radius");
    }
    return;
  }
  if (trigger.at("extent").size() != 3 || !std::isfinite(trigger.at("yaw").get<double>())) {
    throw std::runtime_error("Invalid quest catalog trigger box");
  }
}

void validate_loot_pack(const Json &pack) {
  const double pack_rate = pack.at("pack_rate_percent").get<double>();
  const auto &groups = pack.at("groups");
  if (!std::isfinite(pack_rate) || pack_rate <= 0.0 || pack_rate > 100.0 || !groups.is_array() ||
      groups.empty() || groups.size() > kMaximumLootGroups) {
    throw std::runtime_error("Invalid quest catalog loot pack");
  }
  for (const auto &group : groups) {
    const double rate = group.at("rate_percent").get<double>();
    if (!std::isfinite(rate) || rate <= 0.0 || rate > 100.0 || group.at("items").empty()) {
      throw std::runtime_error("Invalid quest catalog loot group");
    }
    for (const auto &item : group.at("items")) {
      const int minimum = item.at("min_quantity");
      const int maximum = item.at("max_quantity");
      if (item.at("item_cms_id").get<int>() < 0 || minimum <= 0 || maximum < minimum ||
          maximum > kMaximumLootQuantity || item.at("weight").get<int>() <= 0) {
        throw std::runtime_error("Invalid quest catalog loot item");
      }
    }
  }
}

void validate_accept_rule(const Json &rule) {
  const auto kind = rule.at("kind").get<std::string>();
  if (rule.contains("trigger")) {
    validate_trigger_definition(rule.at("trigger"));
  }
  if (kind == "InteractDoodad") {
    validate_placements(rule.at("doodads"));
  } else if (kind == "InteractMemo") {
    validate_placements(rule.at("memos"));
  } else if (kind == "JobBoard" && rule.at("board_id").get<int>() <= 0) {
    throw std::runtime_error("Invalid quest catalog job board rule");
  } else if (kind == "ServerOffered") {
    for (const auto *field : {"npc_ids", "monster_ids", "doodad_ids", "zone_maps"}) {
      if (!rule.at(field).is_array()) {
        throw std::runtime_error("Invalid quest catalog offered start");
      }
    }
  }
}

void validate_company_fields(const Json &quest) {
  for (const auto &condition : quest.at("conditions")) {
    if (condition.at("kind") != "Company") {
      continue;
    }
    const int company_type = condition.at("company_type").get<int>();
    if (company_type < kFirstCompanyType || company_type > kLastCompanyType ||
        !condition.at("ignore_permit").is_boolean() ||
        !condition.at("is_max_contribution").is_boolean() ||
        condition.at("level").get<int>() < 0 ||
        condition.at("contribution").get<std::int64_t>() < 0) {
      throw std::runtime_error("Invalid quest catalog company condition");
    }
  }
  if (quest.contains("company_unlocks")) {
    for (const auto &unlock : quest.at("company_unlocks")) {
      const int company_type = unlock.at("company_type").get<int>();
      const int level = unlock.at("level").get<int>();
      if (company_type < kFirstCompanyType || company_type > kLastCompanyType || level <= 0 ||
          level > kMaximumCompanyLevel) {
        throw std::runtime_error("Invalid quest catalog company unlock");
      }
    }
  }
  if (quest.contains("company_contribution")) {
    const auto contribution = quest.at("company_contribution").get<std::int64_t>();
    if (contribution < 0 || contribution > kMaximumCompanyContributionReward) {
      throw std::runtime_error("Invalid quest catalog company contribution");
    }
  }
}

void validate_quest_definition(const Json &quest) {
  if (quest.at("cms_id").get<int>() <= 0 || !quest.at("accept").is_array() ||
      !quest.at("conditions").is_array() || !quest.at("progresses").is_array() ||
      quest.at("progresses").size() > kMaximumObjectives || !quest.at("rewards").is_array() ||
      !quest.at("supplies").is_array() || !quest.at("unsupported").is_array() ||
      !quest.at("sequential").is_boolean() || !quest.at("auto_complete").is_boolean() ||
      quest.at("experience").get<std::int64_t>() < 0 ||
      quest.value("require_gold", std::int64_t{0}) < 0) {
    throw std::runtime_error("Invalid quest catalog definition");
  }
  for (const auto &accept : quest.at("accept")) {
    validate_accept_rule(accept);
  }
  for (const auto &objective : quest.at("progresses")) {
    const int count = quest_rules::objective_required_count(objective);
    if (objective.at("sequence").get<int>() <= 0 || objective.at("group").get<int>() <= 0 ||
        count <= 0 || count > kMaximumObjectiveCount) {
      throw std::runtime_error("Invalid quest catalog objective");
    }
    if (objective.contains("trigger")) {
      validate_trigger_definition(objective.at("trigger"));
    }
    if (objective.contains("memos")) {
      validate_placements(objective.at("memos"));
    }
  }
  for (const auto *field : {"rewards", "supplies", "require_items"}) {
    if (!quest.contains(field)) {
      continue;
    }
    for (const auto &item : quest.at(field)) {
      if (item.at("item_cms_id").get<int>() < 0 || item.at("quantity").get<int>() <= 0 ||
          item.at("quantity").get<int>() > 1000000) {
        throw std::runtime_error("Invalid quest catalog item reward");
      }
    }
  }
  for (const auto &pack : quest.value("loot_packs", Json::array())) {
    validate_loot_pack(pack);
  }
  const auto guild_experience = quest.value("guild_experience", std::int64_t{0});
  if (guild_experience < 0 || guild_experience > kMaximumGuildExperienceReward) {
    throw std::runtime_error("Invalid quest catalog guild experience");
  }
  validate_company_fields(quest);
}

