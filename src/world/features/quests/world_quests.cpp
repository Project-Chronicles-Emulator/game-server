QuestResult error_result(const std::string &code, std::uint32_t sequence) {
  QuestResult result;
  result.packets.push_back(
      {kCommonError, {{"ec", code}, {"packet_seq", {{"seq", std::to_string(sequence)}}}}});
  return result;
}

